  /* =====================================================
     16. WEBSITE ROUTER
  ===================================================== */

  function route() {
    const hash = decodeURIComponent(
      location.hash.replace(/^#/, "")
    ) || "home";

    document.title = SETTINGS.siteName;

    let html = "";
    let nav = "home";

    const post = ACTIVE_POSTS.find(
      article => article.slug === hash
    );

    if (query) {
      const q = query.toLowerCase();

      const found = sorted().filter(article => {
        const searchable = [
          article.title,
          article.excerpt,
          article.category,
          postTags(article).join(" "),
          article.content
        ].join(" ").toLowerCase();

        return searchable.includes(q);
      });

      html = listView(
        found,
        `Results for "${query}"`,
        "none",
        false
      );

    } else if (post) {
      html = postView(post);
      nav = "";

    } else if (hash === "about") {
      html = aboutView();
      document.title = "About Kabaka | " + SETTINGS.siteName;
      nav = "about";

    } else if (hash === "contact") {
      html = contactView();
      document.title = "Contact | " + SETTINGS.siteName;
      nav = "contact";

    } else if (hash.startsWith("cat-")) {
      const slug = hash.slice(4);

      const category =
        cats().find(item => slugify(item) === slug) || slug;

      html = listView(
        sorted().filter(article =>
          slugify(article.category) === slug
        ),
        category,
        slug,
        false
      );

    } else if (hash.startsWith("tag-")) {
      const slug = hash.slice(4);

      html = listView(
        sorted().filter(article =>
          postTags(article).some(tag => slugify(tag) === slug)
        ),
        `Tagged #${slug}`,
        "none",
        false
      );

    } else {
      html = listView(
        sorted(),
        "Latest posts",
        "all",
        true
      );
    }

    app.innerHTML = html;

    upgradeArticleImages();

    document.querySelectorAll(".nav a").forEach(link => {
      link.classList.toggle(
        "active",
        link.getAttribute("href") === "#" + nav
      );
    });

    const navigation = $("#nav");

    if (navigation) {
      navigation.classList.remove("open");
    }

    bind();

    // The Follow My Blog buttons lead to the homepage newsletter.
    if (hash === "subscribe") {
      requestAnimationFrame(() => {
        $("#subscribe")?.scrollIntoView({
          behavior: "smooth",
          block: "center"
        });
      });
    } else if (!query) {
      window.scrollTo(0, 0);
    }
  }

